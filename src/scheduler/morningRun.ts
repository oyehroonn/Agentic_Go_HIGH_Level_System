import { existsSync, mkdirSync, writeFileSync } from "node:fs";
import { getConfig } from "../config/env.js";
import { runAgent } from "../agent/loop.js";
import { buildContext } from "../runtime/context.js";
import { log } from "../audit/logger.js";
import "../tools/index.js"; // register all tools

/**
 * The autonomous daily job (Flow C). Runs the pipeline-review flow unattended,
 * writes a dated report to data/reports/, and leaves any follow-up messages as
 * pending approvals. Invoke via `npm run schedule` (a cron can call that). §16.
 */

const REPORTS_DIR = "data/reports";

export async function runMorning(): Promise<string> {
  const cfg = getConfig();
  const ctx = buildContext();

  const goal = `Run the daily pipeline review for this location.
1. List the pipelines.
2. Search open opportunities.
3. Identify deals with no status/stage change in more than ${cfg.STALE_OPPORTUNITY_DAYS} days (treat createdAt/updatedAt/lastStatusChangeAt as the activity signal).
4. For each stale deal that has a linked contact, draft a short, friendly follow-up message via send_message (it will be staged for approval — do not expect it to send now).
5. Finish with a concise summary: how many opportunities reviewed, which were stale, and how many follow-ups you staged.`;

  log.info("morningRun.start", { staleDays: cfg.STALE_OPPORTUNITY_DAYS });

  const result = await runAgent(goal, ctx, (e) => {
    if (e.type === "tool_decision") log.info("morningRun.tool", e.text);
  });

  // Append the run summary to location memory for tomorrow's context.
  ctx.memory.recordAction(ctx.locationId, `Morning run: ${result.report.slice(0, 200)}`);

  const stamp = new Date().toISOString().slice(0, 10);
  if (!existsSync(REPORTS_DIR)) mkdirSync(REPORTS_DIR, { recursive: true });
  const reportPath = `${REPORTS_DIR}/${stamp}.md`;
  const contents = `# Pipeline review — ${stamp}\n\n_Generated by GHL ClaudeBot morning run (${result.stoppedReason}, ${result.iterations} iterations)._\n\n${result.report}\n`;
  writeFileSync(reportPath, contents, "utf8");

  log.info("morningRun.done", { reportPath });
  console.log(`\nReport written to ${reportPath}. Review staged follow-ups with the CLI /approvals.`);
  return reportPath;
}
